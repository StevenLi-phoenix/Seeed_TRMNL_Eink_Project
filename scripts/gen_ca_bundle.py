#!/usr/bin/env python3
"""Generate src/x509_crt_bundle.c: the CA bundle WiFiClientSecure verifies the
server certificate against (see lib/trmnl/include/http_client.h).

Binary format = ESP-IDF v4.4 gen_crt_bundle.py, which is what arduino-esp32
2.0.x's WiFiClientSecure/src/esp_crt_bundle.c parses:
  u16be count, then per certificate (sorted by DER subject for binary search):
  u16be name_len, u16be key_len, subject DER, SubjectPublicKeyInfo DER.

Usage (scripts/update_ca_bundle.sh downloads curl's Mozilla extract first):
  uv run --with cryptography python -I scripts/gen_ca_bundle.py \
      --input /tmp/x/cacert.pem scripts/ca/extra_roots.pem --out src/x509_crt_bundle.c
"""
import argparse
import hashlib
import re
import struct
import sys

from cryptography import x509
from cryptography.hazmat.primitives import serialization


def load(path):
    data = open(path, 'rb').read()
    certs = x509.load_pem_x509_certificates(data)
    m = re.search(rb'Certificate data from Mozilla as of: ([^\n]+)', data)
    return certs, hashlib.sha256(data).hexdigest(), (m.group(1).decode() if m else None)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--input', nargs='+', required=True, help='PEM files (Mozilla bundle first, then extras)')
    ap.add_argument('--out', required=True, help='C file to write')
    args = ap.parse_args()

    entries = {}   # (subject_der, spki_der) -> subject string
    subjects = {}  # subject_der -> spki_der
    provenance = []
    for path in args.input:
        certs, digest, mozilla_date = load(path)
        added = 0
        for crt in certs:
            name = crt.subject.public_bytes()
            key = crt.public_key().public_bytes(serialization.Encoding.DER,
                                                serialization.PublicFormat.SubjectPublicKeyInfo)
            if name in subjects and subjects[name] != key:
                # the on-device lookup is a binary search by subject name: two
                # keys under one name would make one of them unreachable
                sys.exit('error: %s appears with two different keys' % crt.subject.rfc4514_string())
            if (name, key) not in entries:
                entries[(name, key)] = crt.subject.rfc4514_string()
                subjects[name] = key
                added += 1
        provenance.append('%s: %d certs (%d new), sha256 %s%s' % (
            path.rsplit('/', 1)[-1], len(certs), added, digest,
            ', Mozilla data as of ' + mozilla_date if mozilla_date else ''))
        print(provenance[-1], file=sys.stderr)

    ordered = sorted(entries.keys(), key=lambda nk: nk[0])
    bundle = bytearray(struct.pack('>H', len(ordered)))
    for name, key in ordered:
        bundle += struct.pack('>HH', len(name), len(key)) + name + key

    lines = [
        '// GENERATED by scripts/gen_ca_bundle.py - do not edit; run scripts/update_ca_bundle.sh',
        '// Trust anchors for TLS server-certificate verification (WiFiClientSecure::setCACertBundle).',
    ]
    lines += ['// ' + p for p in provenance]
    lines += [
        '// %d certificates, %d bytes' % (len(ordered), len(bundle)),
        '#include "x509_crt_bundle.h"',
        '',
        'const uint8_t x509_crt_bundle[] = {',
    ]
    for i in range(0, len(bundle), 16):
        lines.append('  ' + ' '.join('0x%02x,' % b for b in bundle[i:i + 16]))
    lines += ['};', 'const size_t x509_crt_bundle_len = sizeof(x509_crt_bundle);', '']
    with open(args.out, 'w') as f:
        f.write('\n'.join(lines))
    print('wrote %s: %d certificates, %d bytes' % (args.out, len(ordered), len(bundle)), file=sys.stderr)


if __name__ == '__main__':
    main()
